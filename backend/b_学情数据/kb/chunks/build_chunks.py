def _write_jsonl(all_kps: list, out_path: Path, *, version: str) -> int:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with open(out_path, "w", encoding="utf-8") as f:
        for kp_id, kp_name, chunks in all_kps:
            for i, content in enumerate(chunks, 1):
                # 生成 chunk_id：c-{kp_id}-{序号}
                cid = f"c-{kp_id}-{i:02d}"
                obj = {
                    "chunk_id": cid,
                    "doc_id": f"doc-{version}-{kp_id}",
                    "content": content,
                    "embedding": None,  # MVP 阶段无需真实向量
                    "kp_tags": [kp_id],
                    "source_url": f"https://kb.local/{version}/{kp_id}#{i:02d}",
                    "version": version,
                    "seq_index": i,
                }
                f.write(json.dumps(obj, ensure_ascii=False) + "\n")
                count += 1
    return count


